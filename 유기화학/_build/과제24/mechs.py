# -*- coding: utf-8 -*-
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "강의번역24"))
from mech import panel as P, step as S, mrow as R

O0 = {0: (1, 3, 0)}  # C→N 가로

# 호프만 자리옮김 — 손글씨용
def hof(RM, RP, sz=1.0):
    def f(x):
        return x.replace("[*:7]", RM).replace("[*]", RP)
    W = lambda w: int(w * sz)
    return [
 R(P(f('[*][C:1](=[O:2])[N:3]([H:4])[H].[OH-:5]'), [(5, 4, -0.5), ((3, 4), 3, -0.6)], w=W(170), h=W(120), ori=O0, pos=[(4, 5, 1.3, 0.2)], note='① OH⁻가 N–H 떼기'),
   S('', '−H₂O'),
   P(f('[*][C:1](=[O:2])[NH-:3].[Br:4][Br:5]'), [(3, 4, 0.5), ((4, 5), 5, 0.6)], w=W(190), h=W(110), ori={0: (1, 3, 0), 1: (4, 5, 0)}, pos=[(3, 4, 1.9, 0)], note='② N⁻ → Br–Br'),
   S('', '−Br⁻'),
   P(f('[*][C:1](=[O:2])[N:3]([Br])[H:4].[OH-:5]'), [(5, 4, -0.5), ((3, 4), 3, -0.6)], w=W(170), h=W(120), ori=O0, pos=[(4, 5, 1.3, 0.2)], note='③ 남은 N–H 떼기')),
 R(P(f('[*:7][C:1](=[O:2])[N-:3][Br:4]'), [((1, 7), 3, -0.6), ((3, 4), 4, -0.9)], w=W(170), h=W(120), ori=O0, note='④ 알킬기가 N으로 + Br⁻ 이탈'),
   S('', '−Br⁻'),
   P(f('[*][N:3]=[C:1]=[O:2].[OH-:5]'), [(5, 1, 0.4), ((1, 2), 2, 0.6)], w=W(170), h=W(110), ori={0: (3, 2, 0)}, pos=[(1, 5, 0, -1.3)], note='⑤ 아이소사이아네이트 + OH⁻'),
   S('H₂O', ''),
   P(f('[*]NC(=O)O'), w=W(100), h=W(90), note='카밤산'),
   S('⑥ −CO₂', ''),
   P(f('[*]N'), w=W(60), h=W(60), note='1차 아민')),
    ]

def cur(RM, RP, sz=1.0, wy=-1.3):
    def f(x):
        return x.replace("[*:7]", RM).replace("[*]", RP)
    W = lambda w: int(w * sz)
    return [
 R(P(f('[*][C:1](=[O:2])[Cl:3].[N-:4]=[N+]=[N-:8]'), [(4, 1, 0.4), ((1, 3), 3, 0.5)], w=W(210), h=W(130), ori={0: (1, 3, -90), 1: (4, 8, 180)}, pos=[(1, 4, -1.5, -0.2)], note='① N₃⁻ 아실 치환'),
   S('', '−Cl⁻'),
   P(f('[*:7][C:1](=[O:2])[N:3]=[N+:4]=[N-:5]'), [((1, 7), 3, -0.6), ((3, 4), 4, -0.9)], w=W(210), h=W(110), ori={0: (3, 5, 0)}, note='② 가열: 알킬기가 N으로 + N₂ 이탈'),
   S('Δ', '−N₂')),
 R(P(f('[*][N:3]=[C:1]=[O:2].[OH2:5]'), [(5, 1, 0.4 if wy < 0 else -0.4), ((1, 2), 2, 0.6 if wy < 0 else -0.6)], w=W(170), h=W(120), ori={0: (3, 2, 0)}, pos=[(1, 5, 0, wy)], note='③ 아이소사이아네이트 + H₂O'),
   S('', '양성자 이동'),
   P(f('[*]NC(=O)O'), w=W(100), h=W(90), note='카밤산'),
   S('④ −CO₂', ''),
   P(f('[*]N'), w=W(60), h=W(60), note='1차 아민')),
    ]
