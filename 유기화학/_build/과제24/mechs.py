# -*- coding: utf-8 -*-
"""24-32 호프만 · 24-33 커티어스 메커니즘 — 해설집(SSM 24.32·24.33)과 같은 단계 전부, 곡선 화살표.
[*:7] = 이동하는 알킬기(붙는 원자 번호 7), [*] = 같은 알킬기(번호 없음)."""
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "강의번역24"))
from mech import panel as P, step as S, mrow as R

H = {0: (1, 3, 0)}  # C→N 가로

# 아이소사이아네이트 + OH⁻ → 카밤산 / 카밤산 → 아민 + CO₂ (두 메커니즘 공통 끝부분)
def _tail(f, W, n0):
    c = "①②③④⑤⑥⑦⑧"
    return [
     P(f('[*][N:3]=[C:1]=[O:2].[OH-:5].[H:6][OH:8]'), [(5, 1, -0.4), ((1, 3), 6, 0.5), ((6, 8), 8, 0.6)], w=W(200), h=W(140),
       ori={0: (3, 2, 0), 2: (6, 8, 0)}, pos=[(1, 5, 0.3, -1.3), (3, 6, 0.4, 1.3)], note=f'{c[n0]} OH⁻가 C 공격, N이 물의 H를 받음'),
     S('', ''),
     P(f('[*][NH:3][C:1](=[O:2])[O:9][H:10].[H:6][OH:8]'), [((9, 10), (1, 9), 0.6), ((1, 3), 6, -0.5), ((6, 8), 8, -0.6)], w=W(200), h=W(140),
       ori={0: (3, 1, 0), 1: (6, 8, 180)}, pos=[(3, 6, -0.4, 1.5)], note=f'{c[n0+1]} 카밤산 → C=O 생기며 C–N 끊김'),
     S('', '−CO₂'),
     P(f('[*]N'), w=W(80), h=W(70), note='1차 아민 + CO₂ + OH⁻'),
    ]


def hof(RM, RP, sz=1.0):
    f = lambda x: x.replace("[*:7]", RM).replace("[*]", RP)
    W = lambda w: int(w * sz)
    t = _tail(f, W, 4)
    return [
     R(P(f('[*][C:1](=[O:2])[N:3]([H:4])[H].[OH-:5]'), [(5, 4, -0.5), ((3, 4), 3, -0.6)], w=W(180), h=W(120), ori=H, pos=[(4, 5, 1.3, 0.2)], note='① OH⁻가 N–H 떼기'),
       S('', ''),
       P(f('[*][C:1](=[O:2])[NH-:3].[Br:4][Br:5]'), [(3, 4, 0.5), ((4, 5), 5, 0.6)], w=W(200), h=W(110), ori={0: (1, 3, 0), 1: (4, 5, 0)}, pos=[(3, 4, 1.9, 0)], note='② N⁻가 Br–Br 공격 (Br⁻ 이탈)'),
       S('', '−Br⁻'),
       P(f('[*][C:1](=[O:2])[N:3]([Br])[H:4].[OH-:5]'), [(5, 4, -0.5), ((3, 4), 3, -0.6)], w=W(180), h=W(120), ori=H, pos=[(4, 5, 1.3, 0.2)], note='③ 남은 N–H 떼기'),
       S('', '')),
     R(P(f('[*:7][C:1]([O-:2])=[N:3][Br:4]'), [(2, (1, 2), 0.5), ((1, 7), 3, -0.8), ((3, 4), 4, -0.9)], w=W(230), h=W(160), scale=36, ori={0: (7, 1, 0)}, note='④ O⁻ → C=O, 알킬기가 N으로, Br⁻ 이탈'),
       S('', '−Br⁻'),
       *t[:2]),
     R(*t[2:]),
    ]


def cur(RM, RP, sz=1.0):
    f = lambda x: x.replace("[*:7]", RM).replace("[*]", RP)
    W = lambda w: int(w * sz)
    t = _tail(f, W, 3)
    return [
     R(P(f('[*][C:1](=[O:2])[Cl:3].[N-:4]=[N+]=[N-:8]'), [(4, 1, 0.4), ((1, 2), 2, 0.6)], w=W(220), h=W(130), ori={0: (1, 3, -90), 1: (4, 8, 180)}, pos=[(1, 4, -1.5, -0.2)], note='① N₃⁻가 C=O 탄소 공격'),
       S('', ''),
       P(f('[*][C:1]([O-:2])([Cl:3])[N:4]=[N+]=[N-:8]'), [(2, (1, 2), 0.5), ((1, 3), 3, 0.5)], w=W(220), h=W(140), ori={0: (1, 4, 0)}, note='② 사면체 중간체: C=O 복구, Cl⁻ 이탈'),
       S('', '−Cl⁻')),
     R(P(f('[*:7][C:1](=[O:2])[N:3]=[N+:4]=[N-:5]'), [((1, 7), 3, -0.8), ((3, 4), 4, -0.9)], w=W(260), h=W(150), scale=34, ori={0: (3, 5, 0)}, note='③ 가열: 알킬기가 N으로, N₂ 이탈'),
       S('Δ', '−N₂'),
       *t[:2]),
     R(*t[2:]),
    ]
