HERE = os.path.dirname(os.path.abspath(__file__))
_real_page = lib.page

def _record(*a, **k):
    return (a, k)

def _load(folder):
    """다른 주차 content.py를 lib.page 대신 기록기로 돌려 페이지 인자만 받아 온다."""
    lib.page = _record
    try:
        spec = importlib.util.spec_from_file_location(f'content_{folder}', os.path.join(HERE, '..', folder, 'content.py'))
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        return mod
    finally:
        lib.page = _real_page

w10 = _load('w10_blank')
w11 = _load('w11_blank')

PAGES = []
def add(*a, **k): PAGES.append(_real_page(len(PAGES) + 1, *a, **k))

def reuse(rec, slide, title=None, sub=None, **extra):
    (no, t, s, _slide, *rest), k = rec
    k = dict(k); k.pop('img', None); k.update(extra)
    add(title or t, sub or s, slide, *rest, **k)

def find(mod, prefix):
    hits = [r for r in mod.PAGES if r[0][1].startswith(prefix)]
    assert len(hits) == 1, prefix
    return hits[0]

def choices(items, ans):
    nums = '①②③④⑤'
    return '<p>' + '<br>'.join((A(f'{nums[i]} {c}') if i + 1 == ans else f'{nums[i]} {c}') for i, c in enumerate(items)) + '</p>'

def flow(rows):
    icon = {'see': '👀 단서', 'ask': '🤔 질문', 'link': '💡 연결', 'calc': '🧮 계산', 'chk': '🔍 함정체크', 'done': '✅ 결론'}
    return tbl(['🧭 사고의 흐름', ''], [[icon[k], v] for k, v in rows])

def quiz(year, slide, title, kw, summ, q, items, ans, fl, extra=''):
    add(f'Quiz — {year} 기출: {title} (정답 {"①②③④⑤"[ans-1]})', f'Past exam {year}', slide, kw, summ,
        f'<p><b>{year} 기출</b> {q}</p>' + choices(items, ans) + extra,
        flow(fl[0]) + fl[1], left_title='문제 (정답 표시)')

