def ph_graph(kind, w=200, h=130):
    """log k_obs vs pH 개형: down(산촉매, 기울기 −1), up(염기촉매, +1), v(전체)"""
    x0, y0, x1, y1 = 34, 10, w - 8, h - 22
    if kind == 'down':
        path = f'M{x0+6},{y0+6} L{x1-10},{y1-6}'; note = '기울기 −1'
    elif kind == 'up':
        path = f'M{x0+6},{y1-6} L{x1-10},{y0+6}'; note = '기울기 +1'
    else:
        mx = x0 + (x1 - x0) * 0.3
        path = f'M{x0+6},{y0+30} L{mx},{y1-8} L{x1-8},{y0+4}'; note = 'pH 3 부근 최소'
